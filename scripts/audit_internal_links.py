#!/usr/bin/env python3
from pathlib import Path
from urllib.parse import urljoin, urlparse, unquote
from bs4 import BeautifulSoup
import sys
ROOT=Path(__file__).resolve().parents[1]
DIST=ROOT/'dist'
issues=[]; checked=0
htmls=list(DIST.rglob('*.html'))
for file in htmls:
    rel=file.relative_to(DIST).as_posix()
    page_url='https://finance-os.invalid/' + (rel.rsplit('/',1)[0]+'/' if file.name=='index.html' and '/' in rel else '' if rel=='index.html' else rel)
    try: soup=BeautifulSoup(file.read_text(encoding='utf-8',errors='replace'),'html.parser')
    except Exception as e:
        issues.append((rel,'parse',str(e))); continue
    ids={x.get('id') for x in soup.select('[id]')}
    for a in soup.select('a[href]'):
        href=a.get('href','').strip()
        if not href or href.startswith(('mailto:','tel:','javascript:','data:')): continue
        u=urljoin(page_url,href); parsed=urlparse(u)
        if parsed.netloc!='finance-os.invalid': continue
        path=unquote(parsed.path)
        if path in ('','/'): target=DIST/'index.html'
        else:
            target=DIST/path.lstrip('/')
            if path.endswith('/'): target=target/'index.html'
            elif target.is_dir(): target=target/'index.html'
        checked+=1
        if not target.exists():
            issues.append((rel,'missing',href)); continue
        if parsed.fragment and (target.suffix=='.html'):
            try: ts=BeautifulSoup(target.read_text(encoding='utf-8',errors='replace'),'html.parser')
            except: ts=None
            if ts and parsed.fragment not in {x.get('id') for x in ts.select('[id]')}:
                # Some legacy anchors are generated by runtime and cannot be validated as static.
                if parsed.path==page_url.replace('https://finance-os.invalid',''):
                    issues.append((rel,'missing-anchor',href))
print(f'HTML files: {len(htmls)}; internal links checked: {checked}; issues: {len(issues)}')
for issue in issues[:100]: print(' -',*issue)
if issues: sys.exit(1)
